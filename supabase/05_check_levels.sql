       level_from_xp(e.xp)     as got_level_at_xp,
       level_from_xp(e.xp - 1) as got_level_before
from expected e
where xp_for_level(e.lvl) <> e.xp
   or level_from_xp(e.xp) <> e.lvl
   or level_from_xp(e.xp - 1) >= e.lvl;

