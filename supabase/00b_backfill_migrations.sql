-- ============================================================================
-- Шаг 0b: отметить уже применённые шаги (только для существующей базы).
--
-- Если шаги 01..23 вы уже выполняли в SQL Editor ещё до появления учёта,
-- база о них не знает, и первый же assert_migration решит, что можно
-- запускать старый файл. Этот скрипт записывает 01..25 как применённые,
-- чтобы повторный запуск старых файлов упирался в защиту.
--
-- Не запускайте его на пустой базе: тогда шаги 01..25 не будут выполнены.
-- Шаг 24_hardening.sql здесь НЕ отмечается — его нужно применить после.
-- ============================================================================

select register_migration(filename)
from migration_order
where idx <= 25
order by idx;
