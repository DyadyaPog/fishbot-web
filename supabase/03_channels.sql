-- ============================================================================
-- Шаг 3: каналы.
--
-- Один канал = один Twitch ID (broadcaster), у которого работает бот.
-- channel_id из этой таблицы используется во всех игровых таблицах,
-- поэтому страница не привязана к каналу в конфиге.
--
-- Запускать в Supabase → SQL Editor. Скрипт идемпотентен.
-- ============================================================================

create table if not exists channels (
    id           bigint      primary key,   -- числовой Twitch ID канала
    login        text        not null unique, -- логин канала, строчными
    display_name text,                       -- отображаемое имя на Twitch
    created_at   timestamptz not null default now()
);

